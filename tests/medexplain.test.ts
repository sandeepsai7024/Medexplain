test('Clinical Safety Classifier: triggers RED emergency routing with country-specific helplines', () => {
  const uk = evaluateMedicineSafety({
    countryCode: 'GB',
    verificationStatus: 'SYNTHETIC_TEST',
    missingFields: [],
    userSymptomText: 'Patient experiencing difficulty breathing and facial swelling',
  });
  assert.equal(uk.level, 'RED');
  assert.equal(uk.emergencyNumber, '999');

  const india = evaluateMedicineSafety({
    countryCode: 'IN',
    verificationStatus: 'WITHDRAWN',
    missingFields: [],
  });
  assert.equal(india.level, 'RED');
  assert.equal(india.emergencyNumber, '112');

  const au = getCountryEmergencyInfo('AU');
  assert.equal(au.emergencyNumber, '000');

  for (const code of ['GB', 'IN', 'US', 'CA', 'AU', 'EU']) {
    const info = getCountryEmergencyInfo(code);
    assert.ok(info.regulatoryStandard.length > 5, `${code} missing regulatoryStandard`);
    assert.ok(info.cards.length >= 2, `${code} expected at least 2 guidance cards`);
    const hasCallablePrimary = info.cards.some(
      (c) => Boolean(c.phoneNumber) && Boolean(c.telHref?.startsWith('tel:'))
    );
    assert.ok(hasCallablePrimary, `${code} missing clickable tel: emergency card`);
    for (const card of info.cards) {
      assert.ok(
        card.officialPortalUrl.startsWith('https://'),
        `${code}:${card.id} officialPortalUrl must use https`
      );
      assert.ok(
        card.whatToShare.length >= 1,
        `${code}:${card.id} missing whatToShare checklist`
      );
    }
  }
});

test('Clinical Safety Classifier: triggers AMBER for missing fields, pending review, or uncertain scan', () => {
  const missing = evaluateMedicineSafety({
    countryCode: 'GB',
    verificationStatus: 'PENDING_REVIEW',
    missingFields: ['storage_instructions'],
  });
  assert.equal(missing.level, 'AMBER');
  assert.ok(missing.reasons.some((r) => r.includes('storage_instructions')));

  const uncertain = evaluateMedicineSafety({
    countryCode: 'IN',
    verificationStatus: 'SYNTHETIC_TEST',
    missingFields: [],
    isUncertainMatch: true,
  });
  assert.equal(uncertain.level, 'AMBER');
});

test('Reminder safety validation: rejects auto-generated dosage schedules and invalid formats', () => {
  const autoAttempt = validateManualReminderInput({
    medicineName: 'Metformin',
    prescribedDose: '500 mg',
    reminderTime: '08:00',
    frequency: 'Once daily',
    startDate: '2026-11-12',
    autoGenerated: true,
  });
  assert.equal(autoAttempt.valid, false);
  assert.match(autoAttempt.error || '', /auto-generated/i);

  const validManual = validateManualReminderInput({
    medicineName: 'Metformin-Synth 500 mg',
    prescribedDose: '1 tablet after breakfast',
    reminderTime: '08:30',
    frequency: 'Once daily',
    startDate: '2026-11-12',
    autoGenerated: false,
  });
  assert.equal(validManual.valid, true);
});

